export function matchEmojis(query: string, limit = 24): Array<{ name: string; char: string }> {
  const q = query.toLowerCase();
  if (!q) return EMOJIS.slice(0, limit);
  const starts: typeof EMOJIS = [];
  const includes: typeof EMOJIS = [];
  for (const e of EMOJIS) {
    if (e.name.startsWith(q)) starts.push(e);
    else if (e.name.includes(q)) includes.push(e);
  }
  return [...starts, ...includes].slice(0, limit);
}
